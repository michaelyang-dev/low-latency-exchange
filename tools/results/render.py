#!/usr/bin/env python3
"""Render docs/results/<family>.md reports from campaign summaries (docs/plan/12 §8).

Numbers in reports come only from summary.json files; tools/results/check_generated.py
fails CI if a report differs from what this script would produce.

usage: render.py [--stdout FAMILY]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FAMILIES = {
    "lob": ["t11a", "t11", "t12"],
    "network": ["t18"],
    "throughput": ["t20"],
    "failover": ["t25"],
    "logger": ["t31"],
}


def render(family: str) -> str:
    out = [f"# Results: {family}", "",
           "_Generated by `tools/results/render.py` from `results/*/summary.json`. Do not edit by hand._", ""]
    found = False
    for target in FAMILIES[family]:
        for p in sorted(ROOT.glob(f"results/*-{target}-*/summary.json")):
            found = True
            s = json.loads(p.read_text())
            out += [f"## {s['campaign']}", "",
                    f"- methodology: `{s.get('methodology', 'unknown')}`; valid runs: {s['runs_valid']}; "
                    f"excluded runs: {s['runs_excluded']}", "",
                    "| Metric | Median | 95% CI | Min | Max | Runs |", "|---|---|---|---|---|---|"]
            for k, m in sorted(s["metrics"].items()):
                lo, hi = m["ci95"]
                out.append(f"| {k} | {m['median']:.4g} | [{lo:.4g}, {hi:.4g}] | {m['min']:.4g} | {m['max']:.4g} | {m['runs']} |")
            out.append("")
    if not found:
        out.append("No campaigns yet. Headline numbers come only from the lab hosts (docs/plan/02 §5).")
        out.append("")
    return "\n".join(out)


def main() -> int:
    if len(sys.argv) == 3 and sys.argv[1] == "--stdout":
        sys.stdout.write(render(sys.argv[2]))
        return 0
    d = ROOT / "docs/results"
    d.mkdir(parents=True, exist_ok=True)
    for fam in FAMILIES:
        (d / f"{fam}.md").write_text(render(fam))
    print(f"rendered {len(FAMILIES)} report(s) into {d}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
